#!/usr/bin/env python3
"""PreToolUse: block hand-edits to frontend/api/generated/.

That directory is regenerated by `pnpm -C frontend generate-client`; manual
edits get clobbered. Enforces the AGENTS.md rule for both harnesses: Claude
Code sends `tool_input.file_path`; Codex's `apply_patch` sends the raw patch
in `tool_input.command`, so the touched paths are read from its `*** ... File:`
headers. Exit 2 blocks the tool call and feeds stderr back to the agent.
"""

import json
import os
import re
import sys

GUARDED = "/frontend/api/generated/"
PATCH_HEADER = re.compile(r"^\*\*\* (?:Add|Update|Delete) File: (.+?)\s*$|^\*\*\* Move to: (.+?)\s*$", re.M)


def touched_paths(tool_input: dict) -> list[str]:
    """Paths an edit touches, from either harness's payload shape."""
    direct = tool_input.get("file_path") or tool_input.get("notebook_path")
    if direct:
        return [direct]
    patch = tool_input.get("command")
    if not isinstance(patch, str) or "*** Begin Patch" not in patch:
        return []
    return [a or b for a, b in PATCH_HEADER.findall(patch)]


def main() -> int:
    try:
        data = json.load(sys.stdin)
    except (json.JSONDecodeError, ValueError):
        return 0  # unparseable input -> never block

    paths = touched_paths(data.get("tool_input") or {})
    # Fail CLOSED when no path can be read: a guard must not allow an edit it
    # could not inspect, and a schema/matcher change must not silently disable it.
    if not paths:
        print(
            "Blocked: could not determine the target file path from the tool "
            "payload, so the frontend/api/generated/ guard cannot verify this "
            "edit is safe. Refusing by default. (See AGENTS.md.)",
            file=sys.stderr,
        )
        return 2

    project_dir = data.get("cwd") or os.environ.get("CLAUDE_PROJECT_DIR") or os.getcwd()
    for file_path in paths:
        norm = os.path.abspath(os.path.join(project_dir, file_path)).replace(os.sep, "/")
        if GUARDED in norm:
            print(
                f"Blocked: {file_path} is under frontend/api/generated/, which is "
                "generated from the backend OpenAPI schema. Change the backend "
                "endpoint instead, then run `pnpm -C frontend generate-client`. "
                "(See AGENTS.md.)",
                file=sys.stderr,
            )
            return 2
    return 0


if __name__ == "__main__":
    sys.exit(main())
